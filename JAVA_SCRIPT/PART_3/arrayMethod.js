let cars = ["BMW", "Lamborgani", "Farari", "Marshdish"]
console.log(cars);
console.log('');


console.log("After push : ");
cars.push("Safari")
console.log(cars);
console.log('');


console.log("After Pop : ");
cars.pop();
console.log(cars);
console.log('');


console.log("After unshift : ");
cars.unshift("Safari");
console.log(cars);
console.log('');


console.log("After shift : ");
cars.shift();
console.log(cars);




